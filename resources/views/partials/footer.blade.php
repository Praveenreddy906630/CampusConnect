<!-- GSAP Footer Animation Script -->
<script>
document.addEventListener('DOMContentLoaded', function() {
    // Register ScrollTrigger if not already registered
    if (typeof ScrollTrigger !== 'undefined') {
        gsap.registerPlugin(ScrollTrigger, ScrollToPlugin);
    }

    // Footer entrance animation
    gsap.from(".footer-section", {
        y: 50,
        opacity: 0,
        duration: 0.8,
        stagger: 0.2,
        ease: "power3.out",
        scrollTrigger: {
            trigger: "#footer",
            start: "top 80%",
            end: "bottom 20%",
            toggleActions: "play none none reverse"
        }
    });

    // Social links animation
    gsap.from(".social-link", {
        scale: 0,
        opacity: 0,
        duration: 0.6,
        stagger: 0.1,
        ease: "back.out(1.7)",
        scrollTrigger: {
            trigger: "#footer",
            start: "top 70%",
            toggleActions: "play none none reverse"
        }
    });

    // Footer links hover animations
    document.querySelectorAll('.footer-link').forEach(link => {
        link.addEventListener('mouseenter', function() {
            gsap.to(this, {
                x: 5,
                duration: 0.3,
                ease: "power2.out"
            });
        });
        
        link.addEventListener('mouseleave', function() {
            gsap.to(this, {
                x: 0,
                duration: 0.3,
                ease: "power2.out"
            });
        });
    });

    // Contact items animation
    gsap.from(".contact-item", {
        x: -30,
        opacity: 0,
        duration: 0.6,
        stagger: 0.1,
        ease: "power2.out",
        scrollTrigger: {
            trigger: "#footer",
            start: "top 75%",
            toggleActions: "play none none reverse"
        }
    });

    // Copyright animation
    gsap.from(".footer-copyright", {
        y: 20,
        opacity: 0,
        duration: 0.8,
        ease: "power2.out",
        scrollTrigger: {
            trigger: ".footer-copyright",
            start: "top 90%",
            toggleActions: "play none none reverse"
        }
    });

    // Footer links animation
    gsap.from(".footer-links a", {
        y: 20,
        opacity: 0,
        duration: 0.6,
        stagger: 0.1,
        ease: "power2.out",
        scrollTrigger: {
            trigger: ".footer-links",
            start: "top 90%",
            toggleActions: "play none none reverse"
        }
    });

    // Back to top button functionality
    const backToTopBtn = document.getElementById('back-to-top');
    
    window.addEventListener('scroll', () => {
        if (window.scrollY > 300) {
            gsap.to(backToTopBtn, {
                opacity: 1,
                pointerEvents: 'auto',
                duration: 0.3
            });
        } else {
            gsap.to(backToTopBtn, {
                opacity: 0,
                pointerEvents: 'none',
                duration: 0.3
            });
        }
    });

    backToTopBtn.addEventListener('click', () => {
        gsap.to(window, {
            duration: 1,
            scrollTo: { y: 0 },
            ease: "power2.inOut"
        });
    });

    // Social links hover effects
    document.querySelectorAll('.social-link').forEach(link => {
        link.addEventListener('mouseenter', function() {
            gsap.to(this, {
                scale: 1.1,
                rotation: 10,
                duration: 0.3,
                ease: "power2.out"
            });
        });
        
        link.addEventListener('mouseleave', function() {
            gsap.to(this, {
                scale: 1,
                rotation: 0,
                duration: 0.3,
                ease: "power2.out"
            });
        });
    });
});
</script>